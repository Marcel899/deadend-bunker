"""Cut the defense sprite sheet (assets/src/defense.png, 5 x 3 grid on transparency) into
assets/defense/<name>.png, trimmed to their pixels. Turrets and the flamethrower are also split
into a base and a moving part (head / flame) so the game can aim and animate them.
Run from the project root:  python tools/cut_defense.py
"""
import os, json
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.join(os.path.dirname(__file__), '..')
SRC = os.path.join(ROOT, 'assets', 'src', 'defense.png'); OUT = os.path.join(ROOT, 'assets', 'defense')
NAMES = [['slab', 'sandbags', 'woodwall', 'chainfence', 'jersey'],
         ['spikestrip', 'hedgehog', 'minigun', 'sentry', 'flamer'],
         ['barbwire', 'sandbagnest', 'watchtower', 'electric', 'steelspikes']]
# splits in trimmed-sprite pixels: name -> (part, box (x0, y0, x1, y1) as fractions of the sprite)
SPLITS = {'sentry': [('sentry_head', (0, 0, 1, .46)), ('sentry_base', (0, .46, 1, 1))],
          'minigun': [('minigun_head', (0, 0, 1, .52)), ('minigun_base', (0, .52, 1, 1))],
          'flamer': [('flamer_body', (0, 0, .55, 1)), ('flamer_fire', (.55, 0, 1, 1))]}

def trim(a):
    ys, xs = np.nonzero(a[..., 3] > 20)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]

def main():
    a = np.asarray(Image.open(SRC).convert('RGBA')).copy(); a[a[..., 3] < 20] = 0
    H, W = a.shape[:2]; cw, ch = W / 5, H / 3
    os.makedirs(OUT, exist_ok=True)
    # every sprite is one blob once nearby pixels (grass tufts, the flame) are merged; a blob
    # belongs to the grid cell its centre falls in, and the biggest blob of a cell wins
    lab, n = ndimage.label(ndimage.binary_dilation(a[..., 3] > 0, iterations=6))
    best = {}
    for i, sl in enumerate(ndimage.find_objects(lab), 1):
        size = (sl[0].stop - sl[0].start) * (sl[1].stop - sl[1].start)
        r, c = int(((sl[0].start + sl[0].stop) / 2) // ch), int(((sl[1].start + sl[1].stop) / 2) // cw)
        if size > best.get((r, c), (0,))[0]: best[(r, c)] = (size, i, sl)
    sizes = {}
    for r, row in enumerate(NAMES):
        for c, name in enumerate(row):
            _, i, sl = best[(r, c)]
            cell = a[sl].copy(); cell[lab[sl] != i] = 0
            spr = trim(cell); Image.fromarray(spr).save(os.path.join(OUT, name + '.png'), optimize=True)
            h, w = spr.shape[:2]; print(name, w, h); sizes[name] = [w, h]
            for part, (x0, y0, x1, y1) in SPLITS.get(name, []):
                p = spr[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w)]
                Image.fromarray(p).save(os.path.join(OUT, part + '.png'), optimize=True); print(' ', part, p.shape[1], p.shape[0]); sizes[part] = [p.shape[1], p.shape[0]]
    with open(os.path.join(ROOT, 'js', 'data', 'defense_sprites.js'), 'w') as fh:
        fh.write('/* Generated by tools/cut_defense.py: pixel sizes of assets/defense/*.png */\nvar DE = globalThis.DE = globalThis.DE || {};\nDE.Data = DE.Data || {};\n')
        fh.write('DE.Data.DEF_SPRITES = ' + json.dumps(dict(sorted(sizes.items())), separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main()
